def main():
    files = []  # (path on disk, or text; name in the zip; stored without squeezing)

    def add(source, name, stored=False):
        if isinstance(source, Path) and not source.exists():
            sys.exit(f"{source} is missing")
        files.append((source, f"{NAME}/{name}", stored))

    add(ROOT / "target" / "release" / "viewer.exe", "AussieOutback4x4.exe")
    system = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32"
    for runtime in ["vcruntime140.dll", "vcruntime140_1.dll"]:
        add(system / runtime, runtime)
    add(PLAY.replace("\n", "\r\n"), "Play.bat")
    add(CREDITS.replace("\n", "\r\n"), "CREDITS.txt")
    add(ROOT / "scenes" / "outback.world", "scenes/outback.world")
    for page in sorted((ROOT / "ui").rglob("*")):
        if page.is_file():
            add(page, f"ui/{page.relative_to(ROOT / 'ui').as_posix()}", page.suffix == ".jpg")
    for sound in sorted((ROOT / "assets" / "sounds").glob("*.wav")):
        # A file whose name starts with `_` is there to be listened to, and one with a dot in
        # its name is a take: neither is played.
        if not sound.name.startswith("_") and sound.stem.count(".") == 0:
            add(sound, f"assets/sounds/{sound.name}")

    OUT.mkdir(parents=True, exist_ok=True)
    pack = OUT / f"{NAME}-windows.zip"
    with zipfile.ZipFile(pack, "w", allowZip64=True) as zipped:
        for source, name, stored in files:
            how = zipfile.ZIP_STORED if stored else zipfile.ZIP_DEFLATED
            if isinstance(source, Path):
                zipped.write(source, name, compress_type=how)
            else:
                zipped.writestr(zipfile.ZipInfo(name), source, compress_type=how)
    print(f"{pack}: {len(files)} files, {pack.stat().st_size / 1e6:.0f} MB")

    # The maps: what Play.bat is to have, a line each: NAME VERSION MEGABYTES TITLE.
    lines = []
    for name, title in MAPS:
        scene = ROOT / "assets" / f"{name}.solstice"
        if not scene.exists():
            sys.exit(f"{scene} is missing: bake it first")
        digest = hashlib.sha256()
        with open(scene, "rb") as file:
            for chunk in iter(lambda: file.read(1 << 22), b""):
                digest.update(chunk)
        megabytes = round(scene.stat().st_size / 1e6)
        lines.append(f"{name} {digest.hexdigest()[:12]} {megabytes} {title}")
    (OUT / "maps.txt").write_text("\n".join(lines) + "\n", encoding="ascii", newline="\r\n")
    print(f"{OUT / 'maps.txt'}:")
    for line in lines:
        print(f"    {line}")


main()
